#!/bin/bash
# Карта 7 на ночь: фолды 2, 3, 4 для r32 — добиваем полный OOF главного кандидата.
#
# Почему именно это, а не перебор новых конфигураций. Цель сформулирована в терминах
# полного OOF (0.915 против 0.8996 у чемпиона), а на одном фолде конфигурации
# неразличимы: два прогона ОДНОЙ конфигурации с разными сидами разошлись на 7.0
# пункта PR, тогда как преимущество r32 над базой 5.8. Ещё десять фолд-0 замеров
# не приблизят к цели ни на шаг — нужен один кандидат, измеренный честно.
#
# Фолд 0 у r32 уже посчитан (lora_oof_fold0_r32.parquet), фолд 1 идёт на карте 4.
# После этой очереди будут все пять, и метрику можно будет посчитать вложенно.
#
# Порядок фолдов 2,3,4: если ночь оборвётся, каждый завершённый фолд всё равно
# полезен — метрику можно посчитать по подмножеству и сравнить с базой на тех же
# фолдах. Промежуточные результаты не пропадают.
cd /workspace/counter/exp || exit 1
export CUDA_VISIBLE_DEVICES=7
export HF_HOME=/workspace/.cache/huggingface/
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
PY=../.venv/bin/python

for f in 2 3 4; do
    echo "$(date +%H:%M:%S) [карта 7] r32, фолд $f, 2 эпохи" >> queue_gpu7.log
    LORA_TAG=_r32 LORA_RANK=32 LORA_SEED=0 \
        $PY -u lora_train.py "$f" 2 > "lora_fold${f}_r32.out" 2>&1
    echo "$(date +%H:%M:%S) [карта 7] фолд $f готов" >> queue_gpu7.log
done
echo "$(date +%H:%M:%S) [карта 7] очередь завершена" >> queue_gpu7.log
echo "дальше: полный OOF r32 из lora_oof_fold[0-4]_r32.parquet" >> queue_gpu7.log
