def parse(text):
    """Приёмка строгая: первый прогон принял 202 ответа, годными оказались 2.

    Причина была в том, что у Qwen3.5 по умолчанию включён режим рассуждения, и все
    200 токенов уходили на разбор задания по-английски, а «НАЗВАНИЕ:» встречалось
    внутри самого рассуждения. Лечится enable_thinking=False, но фильтр всё равно
    нужен: пустая проверка формата один раз уже пропустила мусор целиком.
    """
    n = re.findall(r"НАЗВАНИЕ:\s*(.+)", text)
    d = re.findall(r"ОПИСАНИЕ:\s*(.+)", text)
    if not n:
        return None
    name = n[-1].strip().strip('"*` ').strip()
    desc = d[-1].strip().strip('"*` ') if d else ""
    if not (8 <= len(name) <= 200) or len(desc) < 20:
        return None
    if re.search(r"[<>`{}]|\bНАЗВАНИЕ\b|\bdescription\b|\bname\b", name, re.I):
        return None
    cyr = len(re.findall(r"[а-яА-ЯёЁ]", name)) / max(len(name), 1)
    if cyr < 0.35:                      # карточка обязана быть русской
        return None
    return name, desc


def main():
    tok = AutoTokenizer.from_pretrained(MODEL, padding_side="left")
    model = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.bfloat16).cuda().eval()

    jobs = []
    for label, concepts in [(1, POS), (0, NEG)]:
        for c in concepts:
            for i in range(N_PER):
                jobs.append((label, c, i))
    print(f"концептов: {len(POS)} поз + {len(NEG)} нег, вариантов на концепт {N_PER}, "
          f"всего запросов {len(jobs)}", flush=True)

    rows = []
    for s in range(0, len(jobs), BS):
        batch = jobs[s:s + BS]
        prompts = []
        for _, c, i in batch:
            msgs = [{"role": "system", "content": SYS},
                    {"role": "user", "content": TPL.format(rules=RULES_FLAM, concept=c, i=i + 1)}]
            try:
                # без этого Qwen3.5 уходит в рассуждение и до карточки не доезжает
                p = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True,
                                            enable_thinking=False)
            except TypeError:
                p = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
            prompts.append(p)
        enc = tok(prompts, return_tensors="pt", padding=True, truncation=True,
                  max_length=1400).to("cuda")
        with torch.no_grad():
            out = model.generate(**enc, max_new_tokens=200, do_sample=True, temperature=0.95,
                                 top_p=0.92, repetition_penalty=1.1,
                                 pad_token_id=tok.pad_token_id or tok.eos_token_id)
        for (label, c, i), o in zip(batch, out):
            text = tok.decode(o[enc["input_ids"].shape[1]:], skip_special_tokens=True)
            p = parse(text)
            if p:
                rows.append({"name": p[0], "description": p[1], "label": label,
                             "concept": c, "category": "Легковоспламеняющиеся"})
        if s % (BS * 8) == 0:
            print(f"  {s}/{len(jobs)} -> принято {len(rows)}", flush=True)

    out = pd.DataFrame(rows).drop_duplicates(subset="name").reset_index(drop=True)
    out["id"] = [f"synth_{i}" for i in range(len(out))]
    out.to_parquet(ROOT + "exp/synth_flam.parquet")
    print(f"\nготово: {len(out)} карточек ({int(out.label.sum())} поз / "
          f"{int((1-out.label).sum())} нег) -> exp/synth_flam.parquet", flush=True)
    print(f"уникальных концептов в выдаче: {out.concept.nunique()}")
    for _, r in out.head(6).iterrows():
        print(f"  [{r.label}] {r['name'][:80]}")


if __name__ == "__main__":
    main()
