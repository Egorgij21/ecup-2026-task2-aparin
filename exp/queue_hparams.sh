#!/bin/bash
# Последние непроверенные ручки обучения. Всё на фолде 4 — 59 позитивов,
# самый информативный из пяти (у остальных 30-40), шум там ~5.8 пункта PR
# против 7.0-8.1 на прочих. Ориентир для сравнения уже посчитан:
# наш Qwen 4B на фолде 4 даёт AUC 0.9868, PR 0.8857.
#
# Порядок по ожидаемой отдаче:
#   1) СКОРОСТЬ ОБУЧЕНИЯ. Не перебиралась ни разу, стоит 1e-4. У gemma-4-12B на
#      кривой лосса прямо видно, что для неё это много: лосс РОС на отрезке 60-80%
#      (0.1867 -> 0.2052) и не восстановился. Для 4B оптимум тоже мог не совпасть.
#      Берём вилку вокруг текущего: 5e-5 и 2e-4.
#   2) FOCAL LOSS. При 3.6% позитивов подавляющее большинство примеров лёгкие,
#      и обычная CE тратит на них градиент. Ни разу не пробовали.
#   3) ТРИ ЭПОХИ В ЧИСТОМ ВИДЕ. Проверялись только внутри combo, вместе с рангом 32
#      и модулями линейного внимания — то есть три изменения разом, и результат
#      был ниже базы. Отдельно эпохи не мерены.
#
# Каждый прогон ~2.3 часа (три эпохи ~3.4). Всего около 10 часов.
cd /workspace/counter/exp || exit 1
export CUDA_VISIBLE_DEVICES="${CARD:?нужен CARD}"
export HF_HOME=/workspace/.cache/huggingface/
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
PY=../.venv/bin/python
LOG=queue_hparams.log

run() {   # run <тег> <эпох> <переменные...>
    local tag=$1 ep=$2; shift 2
    echo "$(date +%H:%M:%S) [карта $CUDA_VISIBLE_DEVICES] $tag ($*)" >> $LOG
    env "$@" LORA_TAG="$tag" LORA_SEED=0 \
        $PY -u lora_train.py 4 "$ep" > "lora_fold4${tag}.out" 2>&1
    grep -a "Легковоспламеняющиеся:" "lora_fold4${tag}.out" | tail -1 >> $LOG
}

run _lr5e5   2 LORA_LR=5e-5
run _lr2e4   2 LORA_LR=2e-4
run _focal   2 LORA_LOSS=focal
run _ep3     3
echo "$(date +%H:%M:%S) [карта $CUDA_VISIBLE_DEVICES] очередь гиперпараметров завершена" >> $LOG
