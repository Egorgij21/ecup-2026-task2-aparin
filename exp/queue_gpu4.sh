#!/bin/bash
# Очередь на СВОБОДНОЙ карте 4. Своя функция ожидания: смотрит только на процессы
# с CUDA_VISIBLE_DEVICES=4, чтобы не путаться с очередями шестой карты.
#
# (1) r32 на фолде 1. Лечит главную методическую проблему: на одном фолде (40
#     позитивов) конфигурации неразличимы — разброс между двумя прогонами ОДНОЙ
#     конфигурации с разными сидами составил 7.0 пункта PR, а преимущество r32
#     над базой 5.8. Второй фолд уменьшает шум примерно в полтора раза и делает
#     вердикт по рангу проверяемым. Плюс это пятая часть будущего полного OOF:
#     если r32 победит, работа уже сделана.
#
# (2) Синтетика на фолде 0, БАЗОВАЯ конфигурация (r16, 2 эпохи, семплер none).
#     Именно базовая, чтобы эффект синтетики не смешался с эффектом ранга и
#     семплера — сравнивать будем напрямую с уже посчитанным lora_oof_fold0.parquet.
#     Отсеивающая проверка на TF-IDF дала падение PR, но она заведомо не решающая:
#     TF-IDF учит поверхностные токены и синтетика чужого словаря его разбавляет,
#     тогда как LoRA работает семантически. Механизм есть: 0 из 30 пропусков имели
#     свою семью среди позитивов train-фолда, а синтетика даёт 96 концептов
#     против 87 реальных положительных семей.
cd /workspace/counter/exp || exit 1
export CUDA_VISIBLE_DEVICES=4
export HF_HOME=/workspace/.cache/huggingface/
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
PY=../.venv/bin/python

echo "$(date +%H:%M:%S) [карта 4] r32, фолд 1, 2 эпохи" >> queue_gpu4.log
LORA_TAG=_r32 LORA_RANK=32 LORA_SEED=0 \
    $PY -u lora_train.py 1 2 > lora_fold1_r32.out 2>&1
echo "$(date +%H:%M:%S) [карта 4] r32 фолд 1 готов" >> queue_gpu4.log

echo "$(date +%H:%M:%S) [карта 4] синтетика, фолд 0, базовая конфигурация" >> queue_gpu4.log
LORA_TAG=_synth LORA_SYNTH=/workspace/counter/exp/synth_flam.parquet \
    LORA_SYNTH_W=1.0 LORA_SEED=0 \
    $PY -u lora_train.py 0 2 > lora_fold0_synth.out 2>&1
echo "$(date +%H:%M:%S) [карта 4] синтетика готова" >> queue_gpu4.log
