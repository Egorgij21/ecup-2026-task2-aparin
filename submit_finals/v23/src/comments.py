"""Генерация объяснений к вердикту.

Комментарий в метрику не входит, но обязан быть строго 50–300 символов,
иначе решение бракуется на Result-стадии. Поэтому — детерминированные шаблоны,
привязанные к правилам категорий и к реально найденным в тексте признакам.
"""
import re
from typing import List

MIN_LEN, MAX_LEN = 50, 300
# рабочий коридор с запасом от жёстких границ
TARGET_MIN, TARGET_MAX = 70, 285

CAT_BAD = "БАД"
CAT_FLAM = "Легковоспламеняющиеся"

# --- маркеры, которые цитируем в объяснении -------------------------------
_BAD_POS = [
    (r"биологически активн\w* добавк", "«биологически активная добавка»"),
    (r"\bбад\b", "маркировка «БАД»"),
    (r"добавк\w* к пище", "«добавка к пище»"),
    (r"dietary supplement", "«dietary supplement»"),
    (r"\bбиодобавк", "«биодобавка»"),
    (r"не являет[cс]я лекарств", "оговорка «не является лекарством»"),
    (r"свидетельство о государственной регистрац|\bсгр\b", "ссылка на СГР"),
]
_BAD_NEG = [
    (r"не относится к категории бад|не является бад|не относится к бад",
     "прямая оговорка «не относится к категории БАД»"),
    (r"спортивн\w* питани", "позиционирование как спортивное питание"),
    (r"\bпротеин", "протеин"),
    (r"\bbcaa\b|аминокислот", "аминокислоты/BCAA"),
    (r"l-?карнитин", "L-карнитин"),
    (r"креатин", "креатин"),
    (r"\bгейнер", "гейнер"),
    (r"жиросжигател", "жиросжигатель"),
    (r"таблетниц|контейнер для таблеток|пилюльниц", "это таблетница, а не сам продукт"),
]
_FLAM_POS = [
    (r"\bспичк", "спички"),
    (r"хлопушк", "пиротехническая хлопушка"),
    (r"цветной дым|дымов\w* шашк", "дымовое изделие"),
    (r"розжиг|растопк|супер-?ролл", "средство для розжига"),
    (r"сухое горючее", "сухое горючее"),
    (r"газ для заправки|бутан", "газ как самостоятельный товар"),
    (r"\bуголь|брикет", "топливные брикеты/уголь"),
    (r"в комплекте.{0,40}(угл|газ|спичк|топлив)", "горючее входит в комплект"),
    (r"бенгальск|фонтан", "изделие с пиротехническим эффектом"),
]
_FLAM_NEG = [
    (r"\bплита|плитка", "это газовая плита — устройство для использования с топливом"),
    (r"\bмангал|\bгриль|\bбарбекю|казан", "это мангал/гриль — конструкция, а не горючее"),
    (r"горелк", "это горелка — прибор, топливо в комплект не входит"),
    (r"пневматическ", "хлопушка пневматическая, без пиротехнического состава"),
    (r"без спичек", "поставляется без спичек"),
    (r"переходник|адаптер", "это адаптер/переходник"),
    (r"\bдрова", "дрова не являются легковоспламеняющимся товаром"),
]


def _found(text: str, table) -> List[str]:
    out = []
    for pat, human in table:
        if re.search(pat, text):
            out.append(human)
        if len(out) == 3:
            break
    return out


def _fit_length(s: str) -> str:
    """Гарантирует длину в [MIN_LEN, MAX_LEN]."""
    s = re.sub(r"\s+", " ", s).strip()
    if len(s) > TARGET_MAX:
        cut = s.rfind(" ", 0, TARGET_MAX)
        s = (s[:cut] if cut > MIN_LEN else s[:TARGET_MAX]).rstrip(" ,;:-") + "."
    if len(s) < TARGET_MIN:
        s = (s.rstrip(".") + ". Решение принято автоматически по правилам категории "
             "на основании названия и описания карточки товара.")
    if len(s) > MAX_LEN:
        cut = s.rfind(" ", 0, MAX_LEN - 1)
        s = s[:cut if cut > MIN_LEN else MAX_LEN - 1].rstrip(" ,;:-") + "."
    if len(s) < MIN_LEN:
        s = (s + " " * (MIN_LEN - len(s)))
    return s


def make_comment(category: str, text_lower: str, verdict_positive: bool, prob: float) -> str:
    """verdict_positive=True -> товар относится к категории -> вердикт «не бан»."""
    if len(text_lower.strip()) < 8:
        base = ("Карточка почти не содержит текста: названия и описания недостаточно для "
                "надёжной проверки, вердикт вынесен по умолчанию для категории "
                + (category or "товара"))
        return _fit_length(base + ".")

    if category == CAT_BAD:
        if verdict_positive:
            sig = _found(text_lower, _BAD_POS)
            base = (("Карточка содержит прямое указание на биологически активную добавку: "
                     + ", ".join(sig))
                    if sig else
                    ("Явной маркировки БАД в тексте нет, но состав, форма выпуска и назначение "
                     "указывают на биологически активную добавку"))
            base += ". Товар отнесён к категории БАД"
        else:
            sig = _found(text_lower, _BAD_NEG)
            base = ("Прямого указания на биологически активную добавку в карточке нет"
                    + ("; признаки против: " + ", ".join(sig) if sig else "")
                    + ". К категории БАД товар не относится")
    elif category == CAT_FLAM:
        if verdict_positive:
            sig = _found(text_lower, _FLAM_POS)
            base = (("Товар является самостоятельным источником огня либо содержит горючее "
                     "вещество: " + ", ".join(sig))
                    if sig else
                    ("По совокупности признаков описания товар содержит горючее вещество либо "
                     "служит источником открытого огня"))
            base += ". По правилам площадки он относится к легковоспламеняющимся"
        else:
            sig = _found(text_lower, _FLAM_NEG)
            base = ("Товар не является источником воспламенения и не содержит горючего "
                    "вещества в комплекте"
                    + ("; " + ", ".join(sig) if sig else "")
                    + ". К легковоспламеняющимся он не относится")
    else:
        base = ("Автоматическая проверка карточки товара по названию и описанию: "
                "оснований для изменения категории не выявлено")

    return _fit_length(f"{base}. Уверенность модели {prob:.2f}.")


def format_result(comment: str, verdict_positive: bool) -> str:
    """Строгий формат: <комментарий>ТЕКСТ<вердикт>ВЕРДИКТ, без закрывающих тегов."""
    verdict = "не бан" if verdict_positive else "бан"
    return f"<комментарий>{comment}<вердикт>{verdict}"
