"""Промпт для Qwen3.5-4B: официальные правила категорий + карточка товара.

Правила скопированы со страницы «Данные» соревнования дословно.
Смысл подхода: TF-IDF выучил бренды из трейна (Forester, IMAGE, Maclay), которых
в закрытом тесте не будет; LLM с правилами в промпте рассуждает про суть —
«содержит ли товар горючее вещество», «входит ли оно в комплект».
"""
import re

_TAG, _WS = re.compile(r"<[^>]+>"), re.compile(r"\s+")
DESC_CHARS = 1100


def clean(s):
    s = str(s) if s is not None else ""
    if s == "nan":
        s = ""
    s = s.replace("&nbsp;", " ").replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    return _WS.sub(" ", _TAG.sub(" ", s)).strip()


RULES_FLAM = """Правила площадки Ozon для категории «Легковоспламеняющиеся товары».

Товар ЯВЛЯЕТСЯ легковоспламеняющимся, если выполнено хотя бы одно условие:
1. Товар является самостоятельным источником воспламенения — его основное назначение \
создавать или поддерживать открытый огонь. Например: спички, зажигалки, средства для розжига.
2. Товар содержит горючее вещество, легковоспламеняющуюся жидкость или горючий газ. \
Например: газ для заправки, сухое горючее, уголь и топливные брикеты, пиротехнический состав.
3. В комплект товара входит легковоспламеняющийся товар. Например: одноразовый мангал \
с углём в комплекте, горелка, продаваемая вместе с газовым баллоном.

Товар НЕ является легковоспламеняющимся, если:
1. Он не содержит источника воспламенения или горючего вещества. Устройство, \
предназначенное для использования с огнём или горючими веществами, само по себе НЕ \
является легковоспламеняющимся. Например: мангалы, грили, газовые плиты, горелки без баллона.
2. Легковоспламеняющимся является содержимое, а не сама конструкция; без содержимого \
товар не считается легковоспламеняющимся.
3. Источник воспламенения встроен в изделие (например, пьезоподжиг).
4. Потенциально горючий материал используется лишь как компонент другого изделия и не \
является самостоятельным товаром. Например: активированный уголь в фильтрах, уголь для рисования.
5. Легковоспламеняющийся предмет НЕ входит в комплект."""

RULES_BAD = """Правила площадки Ozon для категории «Биологически активные добавки (БАД)».

Товар ЯВЛЯЕТСЯ биологически активной добавкой, если:
1. В описании или на изображении содержится прямое указание, что товар является \
биологически активной добавкой (БАД, dietary supplement, добавка к пище).

Товар НЕ является биологически активной добавкой, если:
1. Товар является спортивным питанием: аминокислоты, BCAA, L-карнитин, креатин, протеин, \
гейнер, предтренировочный комплекс или иной товар с прямым указанием на принадлежность \
к спортивному питанию.
2. В описании явно указано, что товар не является биологически активной добавкой.
3. Товар не содержит маркировок биологически активной добавки (БАД, dietary supplement)."""

QUESTION = {
    "Легковоспламеняющиеся": "Является ли этот товар легковоспламеняющимся по правилам выше?",
    "БАД": "Является ли этот товар биологически активной добавкой по правилам выше?",
}

SYSTEM = ("Ты модератор карточек товаров на маркетплейсе. Ты строго следуешь правилам "
          "площадки. Отвечай ровно одним словом: Да или Нет.")


def build_messages(cat, name, desc):
    rules = RULES_FLAM if cat == "Легковоспламеняющиеся" else RULES_BAD
    question = QUESTION.get(cat, QUESTION["БАД"])
    card = f"Название товара: {clean(name)}\n\nОписание товара: {clean(desc)[:DESC_CHARS]}"
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user",
         "content": f"{rules}\n\n---\n\n{card}\n\n---\n\n{question} Ответь одним словом: Да или Нет."},
    ]


# Прицельный промпт для БАД С КАРТИНКАМИ: называет КОНКРЕТНЫЕ надписи на упаковке,
# которые модель должна ПРОЧИТАТЬ на фото, вместо общих правил площадки. Аналог
# сработал на хлопушках (+0.12 AUC): модель не искала маркировку, пока ей прямо не
# сказали, ЧТО искать. БАД-адаптер v20 обучался ИМЕННО на этом промпте (мы прогоняли
# обучение с PROMPT_VARIANT=badimg), поэтому на прогоне он обязан совпадать —
# иначе train/inference рассинхрон. На полном OOF при фикс. пороге дал БАД
# 0.9487 против 0.9459 (+0.0028). Используется ТОЛЬКО для БАД-адаптера с картинками
# (score_cards_mm); zero-shot ансамбль и флам-адаптеры остаются на build_messages,
# т.к. коэффициенты LogReg обучены на обычном RULES_BAD — менять их нельзя.
_BAD_IMG = ("Внимательно ПРОЧИТАЙ ТЕКСТ НА УПАКОВКЕ на фотографиях. Товар является "
            "БАД, если на упаковке или в описании есть: «БАД», «биологически активная "
            "добавка», «добавка к пище», «dietary supplement», «не является лекарственным "
            "средством», номер свидетельства о государственной регистрации (СГР, RU.77). "
            "Товар НЕ БАД, если это спортивное питание (протеин, BCAA, креатин, гейнер), "
            "лекарство, косметика или обычный продукт питания без такой маркировки.")


def build_messages_badimg(cat, name, desc):
    """Как build_messages, но для БАД подставляет прицельный промпт _BAD_IMG.
    Для флам поведение идентично build_messages. Предназначен ТОЛЬКО для
    мультимодального БАД-адаптера (score_cards_mm)."""
    if cat != "БАД":
        return build_messages(cat, name, desc)
    question = QUESTION["БАД"]
    card = f"Название товара: {clean(name)}\n\nОписание товара: {clean(desc)[:DESC_CHARS]}"
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user",
         "content": f"{_BAD_IMG}\n\n---\n\n{card}\n\n---\n\n{question} Ответь одним словом: Да или Нет."},
    ]


# БАД-варианты для 3-бленда промптов (v22/v23). Адаптеры обучены ИМЕННО с этими
# промптами (PROMPT_VARIANT=noexcl/sportbad) — на прогоне обязаны совпадать. Только БАД.
_BAD_NOEXCL = ("Внимательно ПРОЧИТАЙ ТЕКСТ НА УПАКОВКЕ на фотографиях и в описании. Товар "
               "является БАД, если на упаковке или в описании есть: «БАД», «биологически "
               "активная добавка», «добавка к пище», «dietary supplement», «не является "
               "лекарственным средством», номер свидетельства о государственной регистрации "
               "(СГР, RU.77), или это витамины, минералы, аминокислоты, травяные экстракты и "
               "подобные добавки к пище. Если никаких признаков добавки к пище нет — не БАД.")
_BAD_SPORTBAD = ("Внимательно ПРОЧИТАЙ ТЕКСТ НА УПАКОВКЕ на фотографиях. Товар является БАД, "
                 "если на упаковке или в описании есть: «БАД», «биологически активная добавка», "
                 "«добавка к пище», «dietary supplement», «не является лекарственным средством», "
                 "номер СГР (RU.77). Спортивное питание (протеин, BCAA, аминокислоты, креатин, "
                 "гейнер, L-карнитин, изотоник) ТОЖЕ обычно относят к БАД. Товар НЕ БАД только "
                 "если это лекарство (регистрационное удостоверение, показания к применению), "
                 "косметика для наружного применения или обычный продукт питания.")


def _bad_msg(rules, name, desc):
    card = f"Название товара: {clean(name)}\n\nОписание товара: {clean(desc)[:DESC_CHARS]}"
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user",
         "content": f"{rules}\n\n---\n\n{card}\n\n---\n\n{QUESTION['БАД']} Ответь одним словом: Да или Нет."},
    ]


def build_messages_noexcl(cat, name, desc):
    return _bad_msg(_BAD_NOEXCL, name, desc) if cat == "БАД" else build_messages(cat, name, desc)


def build_messages_sportbad(cat, name, desc):
    return _bad_msg(_BAD_SPORTBAD, name, desc) if cat == "БАД" else build_messages(cat, name, desc)


