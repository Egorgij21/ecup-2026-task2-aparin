def _compile(d):
    return {k: re.compile(v) for k, v in d.items()}


_FLAM_C = _compile(FLAM_RULES)
_BAD_C = _compile(BAD_RULES)


def feature_names(category: str):
    return list((_FLAM_C if category == "Легковоспламеняющиеся" else _BAD_C).keys())


def extract(texts, names, category: str) -> np.ndarray:
    """Бинарные срабатывания правил: отдельно по названию и по всему тексту."""
    rules = _FLAM_C if category == "Легковоспламеняющиеся" else _BAD_C
    out = np.zeros((len(texts), 2 * len(rules)), dtype=np.float32)
    for i, (t, n) in enumerate(zip(texts, names)):
        for j, (_, rx) in enumerate(rules.items()):
            out[i, j] = 1.0 if rx.search(t) else 0.0
            out[i, len(rules) + j] = 1.0 if rx.search(n) else 0.0
    return out
